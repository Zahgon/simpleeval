# Generates tables.go from the running CPython: the module names and codec
# aliases of the encodings package, which of its codecs are not text
# encodings, and the byte tables of every single-byte charmap codec.
#   devtools/py.sh gold/internal/codecs python3 gen.py && gofmt -w tables.go
import codecs
import encodings
import encodings.aliases
import importlib
import os
import sys

NATIVE = {
    'utf_8': 'utf-8', 'utf_8_sig': 'utf-8-sig', 'ascii': 'ascii', 'latin_1': 'iso8859-1',
    'utf_16': 'utf-16', 'utf_16_le': 'utf-16-le', 'utf_16_be': 'utf-16-be',
    'utf_32': 'utf-32', 'utf_32_le': 'utf-32-le', 'utf_32_be': 'utf-32-be',
}


def other_modules(skip):
    """The other codec modules of the encodings package, for the name search
    of ModuleOf: module -> (CodecInfo.name, is a text encoding)."""
    found = {}
    here = os.path.dirname(encodings.__file__)
    for fn in sorted(os.listdir(here)):
        if not fn.endswith('.py') or fn.startswith('_'):
            continue
        name = fn[:-3]
        if name in skip:
            continue
        try:
            mod = importlib.import_module('encodings.' + name)
            info = mod.getregentry()
        except (ImportError, AttributeError):
            continue
        if isinstance(info, codecs.CodecInfo):
            found[name] = (info.name, info._is_text_encoding)
    return found


def charmap_modules():
    found = {}
    here = os.path.dirname(encodings.__file__)
    for fn in sorted(os.listdir(here)):
        if not fn.endswith('.py') or fn.startswith('_'):
            continue
        name = fn[:-3]
        if name in NATIVE:
            continue
        try:
            mod = importlib.import_module('encodings.' + name)
        except ImportError:
            continue
        if not (hasattr(mod, 'decoding_table') or hasattr(mod, 'decoding_map')):
            continue
        info = mod.getregentry()
        if not isinstance(info, codecs.CodecInfo) or not info._is_text_encoding:
            continue
        dec = []
        for i in range(256):
            try:
                s = bytes([i]).decode(info.name)
            except UnicodeDecodeError:
                dec.append(None)
                continue
            if len(s) != 1:
                break
            dec.append(s)
        else:
            found[name] = (info.name, dec, encode_table(info.name, dec))
    return found


def encode_table(name, dec):
    # Characters whose encoding is not the inverse of the decoding table.
    inverse = {}
    for i, ch in enumerate(dec):
        if ch is not None:
            inverse[ch] = i
    extra = []
    for ch in sorted(set(c for c in dec if c is not None)):
        try:
            b = ch.encode(name)
        except UnicodeEncodeError:
            extra.append((ord(ch), -1))
            continue
        if len(b) != 1:
            sys.exit('multi-byte encoding of %r in %s' % (ch, name))
        if b[0] != inverse[ch]:
            extra.append((ord(ch), b[0]))
    # Every other character must be unencodable.
    bad = []

    def handler(exc):
        bad.append((exc.start, exc.end))
        return ('', exc.end)
    codecs.register_error('gen-collect', handler)
    every = ''.join(chr(c) for c in range(0x110000) if not 0xD800 <= c < 0xE000 and chr(c) not in inverse)
    out = every.encode(name, 'gen-collect')
    if out:
        sys.exit('%s encodes characters outside its decoding table' % name)
    return extra


def go_string(chars):
    out = []
    for ch in chars:
        c = 0xFFFE if ch is None else ord(ch)
        out.append('\\u%04x' % c)
    return ''.join(out)


def main():
    charmaps = charmap_modules()
    modules = dict(NATIVE)
    for mod, (name, _, _) in charmaps.items():
        modules[mod] = name
    others = other_modules(set(modules))
    for mod, (name, _) in others.items():
        modules[mod] = name
    aliases = {a: m for a, m in encodings.aliases.aliases.items() if m in modules}
    w = []
    w.append('// Code generated by gen.py from CPython %s; DO NOT EDIT.\n' % sys.version.split()[0])
    w.append('\npackage codecs\n')
    w.append('\n// moduleNames maps each module of the encodings package to the name codecs.lookup reports.\n')
    w.append('var moduleNames = map[string]string{\n')
    for m in sorted(modules):
        w.append('\t%s: %s,\n' % (q(m), q(modules[m])))
    w.append('}\n')
    w.append('\n// nonTextModules are the modules whose codec is not a text encoding\n')
    w.append('// (CodecInfo._is_text_encoding is false), which str.encode and bytes.decode\n')
    w.append('// refuse.\n')
    w.append('var nonTextModules = map[string]bool{\n')
    for m in sorted(others):
        if not others[m][1]:
            w.append('\t%s: true,\n' % q(m))
    w.append('}\n')
    w.append('\n// aliases is encodings.aliases.aliases restricted to those modules.\n')
    w.append('var aliases = map[string]string{\n')
    for a in sorted(aliases):
        w.append('\t%s: %s,\n' % (q(a), q(aliases[a])))
    w.append('}\n')
    w.append('\n// charmapTables holds, per charmap module, its 256-entry decoding table\n')
    w.append('// (U+FFFE marks an undefined byte) and the characters whose encoding differs\n')
    w.append('// from the inverse of that table (-1: not encodable).\n')
    w.append('var charmapTables = map[string]charmapSpec{\n')
    for m in sorted(charmaps):
        _, dec, extra = charmaps[m]
        w.append('\t%s: {\n\t\tdecode: "%s",\n' % (q(m), go_string(dec)))
        if extra:
            w.append('\t\tencodeOverrides: map[rune]int{')
            w.append(', '.join('%d: %d' % e for e in extra))
            w.append('},\n')
        w.append('\t},\n')
    w.append('}\n')
    with open('tables.go', 'w') as f:
        f.write(''.join(w))


def q(s):
    return '"' + s + '"'


main()
